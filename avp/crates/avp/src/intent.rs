/// Enumerate every local branch and read its `.avp-intent.toml` if
/// present. Branches that fail to parse are warned and skipped — one
/// broken intent shouldn't block the rest.
#[instrument(level = "debug", skip_all)]
fn scan_active_intents(repo: &Path) -> Result<Vec<IntentFile>> {
    let branches = list_branches(repo)?;
    let mut intents = Vec::new();
    for branch in branches {
        match read_intent_at_ref(repo, &branch) {
            Ok(Some(intent)) => intents.push(intent),
            Ok(None) => debug!(branch = %branch, "no intent on branch"),
            Err(err) => warn!(branch = %branch, ?err, "intent read failed"),
        }
    }
    Ok(intents)
}

fn list_branches(repo: &Path) -> Result<Vec<String>> {
    let out = run_git(
        repo,
        &["for-each-ref", "--format=%(refname:short)", "refs/heads/"],
    )?;
    Ok(out
        .lines()
        .map(|s| s.trim().to_owned())
        .filter(|s| !s.is_empty())
        .collect())
}

fn read_intent_at_ref(repo: &Path, branch: &str) -> Result<Option<IntentFile>> {
    let spec = format!("{branch}:.avp-intent.toml");
    let Some(out) = run_git_quiet(repo, &["show", &spec])? else {
        return Ok(None);
    };
    let intent = IntentFile::from_toml(&out)?;
    Ok(Some(intent))
}

fn changed_files(repo: &Path, base: &str) -> Result<Vec<String>> {
    let out = run_git(repo, &["diff", "--name-only", base, "--"])?;
    Ok(out
        .lines()
        .map(|s| s.trim().to_owned())
        .filter(|s| !s.is_empty())
        .collect())
}

fn run_git(repo: &Path, args: &[&str]) -> Result<String> {
    let output = Command::new("git")
        .current_dir(repo)
        .args(args)
        .output()
        .with_context(|| format!("spawn git {args:?}"))?;
    if !output.status.success() {
        return Err(anyhow!(
            "git {:?} exited {}: {}",
            args,
            output.status,
            String::from_utf8_lossy(&output.stderr).trim()
        ));
    }
    String::from_utf8(output.stdout).map_err(|e| anyhow!("git stdout not utf-8: {e}"))
}

/// Like `run_git` but treats nonzero exit (e.g., "path doesn't exist on
/// this ref") as `Ok(None)` rather than an error. Used by intent-show
/// where an absent file is the common case.
fn run_git_quiet(repo: &Path, args: &[&str]) -> Result<Option<String>> {
    let output = Command::new("git")
        .current_dir(repo)
        .args(args)
        .output()
        .with_context(|| format!("spawn git {args:?}"))?;
    if !output.status.success() {
        return Ok(None);
    }
    let s = String::from_utf8(output.stdout).map_err(|e| anyhow!("git stdout not utf-8: {e}"))?;
    if s.trim().is_empty() {
        return Ok(None);
    }
    Ok(Some(s))
}

