#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quoted_escapes() {
        assert_eq!(quoted("plain"), "\"plain\"");
        assert_eq!(quoted(r#"with "quote""#), r#""with \"quote\"""#);
        assert_eq!(quoted(r"with\backslash"), r#""with\\backslash""#);
    }

    #[test]
    fn render_claim_round_trips() {
        let req = ClaimRequest {
            repo: std::path::PathBuf::from("/tmp/x"),
            agent_id: "claude-2026-05-01-T01".into(),
            branch: "claude/test".into(),
            goal: "g".into(),
            success_test: "cargo test".into(),
            declared_files: vec!["a.toml".into()],
            allows_overlap_with: vec![],
            expected_pr: None,
            expires_after: None,
            force: false,
        };
        let toml = render_claim_toml(&req).unwrap();
        let parsed = IntentFile::from_toml(&toml).unwrap();
        assert_eq!(parsed.agent_id.as_str(), "claude-2026-05-01-T01");
        assert_eq!(parsed.declared_files, vec!["a.toml".to_owned()]);
    }

    #[test]
    fn render_claim_with_overlap_allowance() {
        let req = ClaimRequest {
            repo: std::path::PathBuf::from("/tmp/x"),
            agent_id: "a".into(),
            branch: "b".into(),
            goal: "g".into(),
            success_test: "t".into(),
            declared_files: vec![],
            allows_overlap_with: vec!["other".into()],
            expected_pr: Some("org/repo#1".into()),
            expires_after: Some("2026-12-31".into()),
            force: false,
        };
        let toml = render_claim_toml(&req).unwrap();
        assert!(toml.contains("expected_pr"));
        assert!(toml.contains("expires_after"));
        let parsed = IntentFile::from_toml(&toml).unwrap();
        assert_eq!(parsed.allows_overlap_with.len(), 1);
        assert_eq!(parsed.expected_pr.as_deref(), Some("org/repo#1"));
    }

    #[test]
    fn render_claim_invalid_agent_fails_fast() {
        let req = ClaimRequest {
            repo: std::path::PathBuf::from("/tmp/x"),
            agent_id: "has space".into(),
            branch: "b".into(),
            goal: "g".into(),
            success_test: "t".into(),
            declared_files: vec![],
            allows_overlap_with: vec![],
            expected_pr: None,
            expires_after: None,
            force: false,
        };
        assert!(render_claim_toml(&req).is_err());
    }
}
