/// Topologically sort active intents into a merge order.
#[instrument(level = "debug", skip_all)]
pub(crate) fn merge_order(repo: &Path) -> Result<ExitCode> {
    let intents = scan_active_intents(repo)?;
    if intents.is_empty() {
        println!("merge-order: 0 active intents");
        return Ok(ExitCode::SUCCESS);
    }

    // Build edges: (earlier opened_at) → (later opened_at) when they
    // share files. The earlier intent merges first; the later one
    // rebases onto main after.
    let mut edges: HashMap<String, BTreeSet<String>> = HashMap::new();
    for a in &intents {
        edges.entry(a.agent_id.to_string()).or_default();
    }
    for i in 0..intents.len() {
        for j in (i + 1)..intents.len() {
            let a = &intents[i];
            let b = &intents[j];
            if a.pattern_overlap(b).is_empty() {
                continue;
            }
            let (first, second) = if a.opened_at <= b.opened_at {
                (a, b)
            } else {
                (b, a)
            };
            edges
                .entry(first.agent_id.to_string())
                .or_default()
                .insert(second.agent_id.to_string());
        }
    }

    // Kahn's algorithm: repeatedly pick a node with no incoming edges.
    let mut incoming: HashMap<String, u32> = intents
        .iter()
        .map(|i| (i.agent_id.to_string(), 0))
        .collect();
    for tos in edges.values() {
        for to in tos {
            *incoming.entry(to.clone()).or_default() += 1;
        }
    }
    let mut order: Vec<String> = Vec::with_capacity(intents.len());
    loop {
        // Stable: pick the lexicographically-smallest agent id with 0 incoming.
        let next = incoming
            .iter()
            .filter(|(_, n)| **n == 0)
            .map(|(k, _)| k.clone())
            .min();
        let Some(next) = next else { break };
        incoming.remove(&next);
        if let Some(tos) = edges.get(&next) {
            for to in tos {
                if let Some(n) = incoming.get_mut(to) {
                    *n = n.saturating_sub(1);
                }
            }
        }
        order.push(next);
    }

    if !incoming.is_empty() {
        return Err(anyhow!(
            "merge-order: cycle in intent DAG ({} nodes unresolved)",
            incoming.len()
        ));
    }

    let by_id: BTreeMap<String, &IntentFile> = intents
        .iter()
        .map(|i| (i.agent_id.to_string(), i))
        .collect();
    for (i, id) in order.iter().enumerate() {
        let intent = by_id.get(id).expect("present by construction");
        let blocks: Vec<String> = edges
            .get(id)
            .map(|s| s.iter().cloned().collect())
            .unwrap_or_default();
        println!("{}. {}  ({})", i + 1, id, intent.branch);
        println!("   declared: {}", intent.declared_files.join(", "));
        if !blocks.is_empty() {
            println!("   blocks:   [{}]", blocks.join(", "));
        }
    }
    Ok(ExitCode::SUCCESS)
}

