/// Report file-touch overlap across every active intent in the repo.
#[instrument(level = "debug", skip_all)]
pub(crate) fn overlap(repo: &Path) -> Result<ExitCode> {
    let intents = scan_active_intents(repo)?;
    if intents.len() < 2 {
        println!("overlap: {} intent(s); nothing to compare", intents.len());
        return Ok(ExitCode::SUCCESS);
    }

    let mut collisions: Vec<(String, String, Vec<String>)> = Vec::new();
    for i in 0..intents.len() {
        for j in (i + 1)..intents.len() {
            let a = &intents[i];
            let b = &intents[j];
            let shared = a.pattern_overlap(b);
            if shared.is_empty() {
                continue;
            }
            if a.overlap_allowed_with(b) {
                continue;
            }
            collisions.push((a.agent_id.to_string(), b.agent_id.to_string(), shared));
        }
    }

    if collisions.is_empty() {
        println!("overlap: clean ({} active intents)", intents.len());
        return Ok(ExitCode::SUCCESS);
    }
    for (a, b, shared) in &collisions {
        println!("overlap: {a} ↔ {b}");
        for f in shared {
            println!("  - {f}");
        }
        println!("  resolution: add `allows_overlap_with = [\"{a}\"]` to one side, or coordinate.");
    }
    Err(anyhow!(
        "{} overlap collision(s) across {} intents",
        collisions.len(),
        intents.len()
    ))
}

