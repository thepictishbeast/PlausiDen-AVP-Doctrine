/// CI gate: load the current branch's intent and check that the diff
/// against `--base` ref doesn't exceed `declared_files`.
#[instrument(level = "debug", skip_all)]
pub(crate) fn verify(repo: &Path, base: &str) -> Result<ExitCode> {
    let intent_path = repo.join(".avp-intent.toml");
    if !intent_path.is_file() {
        return Err(anyhow!(
            "{} missing; every conductor-managed branch must have an intent",
            intent_path.display()
        ));
    }
    let intent = IntentFile::load(&intent_path)?;

    let now = OffsetDateTime::now_utc().date();
    if intent.is_expired(now) {
        return Err(anyhow!(
            "intent expired (expires_after past). archive or refresh the claim."
        ));
    }

    let changed = changed_files(repo, base)?;
    let mut over: Vec<String> = Vec::new();
    for f in &changed {
        if !intent.matches_path(f) && f != ".avp-intent.toml" {
            over.push(f.clone());
        }
    }
    if !over.is_empty() {
        for f in &over {
            eprintln!(
                "::error::file `{f}` is outside declared_files of intent {}",
                intent.agent_id
            );
        }
        return Err(anyhow!(
            "{} file(s) modified outside declared scope",
            over.len()
        ));
    }
    println!(
        "intent verify: clean ({} declared, {} changed)",
        intent.declared_files.len(),
        changed.len(),
    );
    Ok(ExitCode::SUCCESS)
}

