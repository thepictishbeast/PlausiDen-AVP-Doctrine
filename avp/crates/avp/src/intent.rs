//! `avp intent {claim|overlap|merge-order|verify}` — git-aware
//! coordination over `.avp-intent.toml`.
//!
//! Discovery shells to `git`: `git for-each-ref refs/heads/*` to
//! enumerate branches, `git show <ref>:.avp-intent.toml` to read each
//! branch's claim without checking it out.
//!
//! Schema + lifecycle live in `cross-repo/multi-instance.md`. This
//! module is the CLI surface; the parser + types live in
//! `avp_core::intent`.

#![allow(clippy::disallowed_macros)]

use std::{
    collections::{BTreeMap, BTreeSet, HashMap},
    fmt::Write as _,
    fs,
    path::Path,
    process::{Command, ExitCode},
};

use anyhow::{Context as _, Result, anyhow};
use avp_core::{AgentId, IntentFile};
use time::{OffsetDateTime, format_description::well_known::Rfc3339};
use tracing::{debug, info, instrument, warn};

// ─────────────────────────────────────────────────────────────────────────
// claim
// ─────────────────────────────────────────────────────────────────────────

/// Inputs for `avp intent claim`.
#[derive(Debug)]
pub(crate) struct ClaimRequest {
    pub repo: std::path::PathBuf,
    pub agent_id: String,
    pub branch: String,
    pub goal: String,
    pub success_test: String,
    pub declared_files: Vec<String>,
    pub allows_overlap_with: Vec<String>,
    pub expected_pr: Option<String>,
    pub expires_after: Option<String>,
    pub force: bool,
}

/// Top-level entry for `claim`. Validates against active intents on
/// other branches, then writes `.avp-intent.toml` at repo root.
#[instrument(level = "debug", skip_all, fields(repo = %req.repo.display(), agent = %req.agent_id))]
pub(crate) fn claim(req: &ClaimRequest) -> Result<ExitCode> {
    let intent_path = req.repo.join(".avp-intent.toml");
    if intent_path.exists() && !req.force {
        return Err(anyhow!(
            "{} already exists; pass --force to overwrite",
            intent_path.display()
        ));
    }

    // Render TOML deterministically.
    let body = render_claim_toml(req)?;
    // Validate by round-tripping through the parser (catches typos /
    // bad combinations before we write to disk).
    let candidate =
        IntentFile::from_toml(&body).context("rendered claim failed validation; this is a bug")?;

    // Pre-claim conflict check against every other active intent.
    let actives = scan_active_intents(&req.repo).unwrap_or_else(|err| {
        warn!(?err, "intent scan failed; proceeding without overlap check");
        Vec::new()
    });
    let mut conflicts = Vec::new();
    for other in &actives {
        if other.agent_id == candidate.agent_id {
            continue; // re-claiming same intent on same branch is fine
        }
        let shared = candidate.pattern_overlap(other);
        if shared.is_empty() {
            continue;
        }
        if candidate.overlap_allowed_with(other) {
            info!(other = %other.agent_id, files = ?shared, "overlap explicitly allowed");
            continue;
        }
        conflicts.push((other.agent_id.clone(), shared));
    }

    if !conflicts.is_empty() && !req.force {
        for (other, files) in &conflicts {
            eprintln!(
                "::error::intent overlap with {} on files: {}",
                other,
                files.join(", ")
            );
        }
        return Err(anyhow!(
            "{} overlap conflict(s); resolve with allows_overlap_with or pick disjoint files",
            conflicts.len()
        ));
    }

    fs::write(&intent_path, &body).with_context(|| format!("write {}", intent_path.display()))?;
    info!(path = %intent_path.display(), "intent claimed");
    println!(
        "claimed: {} ({} declared file(s))",
        candidate.agent_id,
        candidate.declared_files.len()
    );
    Ok(ExitCode::SUCCESS)
}

/// Render the canonical TOML body for an intent. Field order is fixed
/// so re-claims diff cleanly.
fn render_claim_toml(req: &ClaimRequest) -> Result<String> {
    // Guard: validate the agent id shape now so we fail fast with a
    // shaped error before writing a file that the parser would reject.
    let _ = AgentId::new(req.agent_id.clone()).context("agent_id")?;

    let opened = OffsetDateTime::now_utc()
        .format(&Rfc3339)
        .context("format opened_at")?;

    let mut s = String::new();
    let _ = writeln!(s, "# .avp-intent.toml — generated by `avp intent claim`.");
    let _ = writeln!(
        s,
        "# Schema: PlausiDen-AVP-Doctrine/cross-repo/multi-instance.md"
    );
    let _ = writeln!(s, "agent_id     = {}", quoted(&req.agent_id));
    let _ = writeln!(s, "branch       = {}", quoted(&req.branch));
    let _ = writeln!(s, "goal         = {}", quoted(&req.goal));
    let _ = writeln!(s, "success_test = {}", quoted(&req.success_test));
    let _ = writeln!(s, "opened_at    = {}", quoted(&opened));
    let _ = writeln!(s, "declared_files = [");
    for f in &req.declared_files {
        let _ = writeln!(s, "    {},", quoted(f));
    }
    let _ = writeln!(s, "]");
    if !req.allows_overlap_with.is_empty() {
        let _ = writeln!(s, "allows_overlap_with = [");
        for a in &req.allows_overlap_with {
            let _ = writeln!(s, "    {},", quoted(a));
        }
        let _ = writeln!(s, "]");
    }
    if let Some(pr) = &req.expected_pr {
        let _ = writeln!(s, "expected_pr   = {}", quoted(pr));
    }
    if let Some(exp) = &req.expires_after {
        let _ = writeln!(s, "expires_after = {}", quoted(exp));
    }
    Ok(s)
}

/// TOML basic-string with conservative escaping (covers "" and \).
fn quoted(s: &str) -> String {
    let escaped = s.replace('\\', "\\\\").replace('"', "\\\"");
    format!("\"{escaped}\"")
}

